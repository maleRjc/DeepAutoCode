const TABLES: Record<AppLocale, Dict> = {
  en: { ...en, ...SETTINGS_MESSAGES.en, ...WELCOME_MESSAGES.en },
  'zh-CN': { ...zhCN, ...SETTINGS_MESSAGES['zh-CN'], ...WELCOME_MESSAGES['zh-CN'] },
  'zh-TW': { ...zhTW, ...SETTINGS_MESSAGES['zh-TW'], ...WELCOME_MESSAGES['zh-TW'] },
};

export function getMessage(locale: AppLocale, key: string): string {
  const table = TABLES[locale] || TABLES['zh-CN'];
  return table[key] ?? TABLES['zh-CN'][key] ?? TABLES.en[key] ?? key;
}

export function hasMessage(locale: AppLocale, key: string): boolean {
  return Boolean(TABLES[locale]?.[key] || TABLES['zh-CN'][key] || TABLES.en[key]);
}

export function formatMessage(
  locale: AppLocale,
  key: string,
  vars: Record<string, string | number>
): string {
  let out = getMessage(locale, key);
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}
