const DICTS: Record<Locale, Record<string, string>> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en };

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[locale]?.[key] ?? DICTS['zh-CN'][key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`
  );
}

export function createTranslator(locale: Locale): Translate {
  return (key, vars) => translate(locale, key, vars);
}

export function detectLocale(): Locale {
  const saved = localStorage.getItem('dac.locale');
  if (saved === 'zh-CN' || saved === 'zh-TW' || saved === 'en') return saved;
  const nav = navigator.language.toLowerCase();
  if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk')) return 'zh-TW';
  if (nav.startsWith('zh')) return 'zh-CN';
  return 'en';
}

